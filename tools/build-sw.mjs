#!/usr/bin/env node
// Writes sw.js, the offline helper used when the app is opened from a web address (e.g. GitHub Pages).
// It lists every file the app needs and a version made from their contents, so phones pick up changes.
// Usage: node tools/build-sw.mjs          (rewrite sw.js)
//        node tools/build-sw.mjs --check  (exit 1 if sw.js is out of date; used by the tests)
// Run it after changing any app file, and after node tools/build-words-js.mjs.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const html = readFileSync(resolve(root, 'index.html'), 'utf8');
const scripts = [...html.matchAll(/<script src="([^"]+)"/g)].map((m) => m[1]);
const files = ['index.html', 'css/styles.css', 'manifest.webmanifest',
  'icons/icon-192.png', 'icons/icon-512.png', 'icons/icon-maskable-512.png', 'icons/apple-touch-icon.png', ...scripts];

const hash = createHash('sha256');
for (const f of files) {
  const p = resolve(root, f);
  if (!existsSync(p)) { console.error(`ERROR: ${f} is listed but missing`); process.exit(1); }
  hash.update(f + '\0').update(readFileSync(p));
}
const version = hash.digest('hex').slice(0, 12);

const sw = `// GENERATED by tools/build-sw.mjs. Do not edit by hand.
// Keeps a copy of the app on the device so it opens without internet after the first visit.
const VERSION = '${version}';
const CACHE = 'grand-finale-' + VERSION;
const FILES = ${JSON.stringify(['./'].concat(files), null, 1)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => k.startsWith('grand-finale-') && k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});

// The saved copy first (fast, works offline); the internet only for anything not saved.
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  e.respondWith(caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req)));
});
`;

const out = resolve(root, 'sw.js');
if (process.argv.includes('--check')) {
  const cur = existsSync(out) ? readFileSync(out, 'utf8') : '';
  if (cur !== sw) { console.error('sw.js is out of date. Run: node tools/build-sw.mjs'); process.exit(1); }
  console.log('sw.js is up to date (version ' + version + ')');
} else {
  writeFileSync(out, sw, 'utf8');
  console.log(`sw.js written: ${files.length} files, version ${version}`);
}
